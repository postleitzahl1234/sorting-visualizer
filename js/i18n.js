  const DICT = { en: EN, de: DE };
  const listeners = [];

  const I18N = {
    lang: 'en',
    init(lang) {
      let l = lang;
      if (!DICT[l]) { try { l = localStorage.getItem('sortviz.lang'); } catch (e) { l = null; } }
      if (!DICT[l]) l = (navigator.language || 'en').toLowerCase().startsWith('de') ? 'de' : 'en';
      this.lang = l;
    },
    set(lang) {
      if (!DICT[lang] || lang === this.lang) return;
      this.lang = lang;
      try { localStorage.setItem('sortviz.lang', lang); } catch (e) { /* ignore */ }
      listeners.forEach((fn) => fn(lang));
    },
    onChange(fn) { listeners.push(fn); },
    locale() { return this.lang === 'de' ? 'de-DE' : 'en-US'; },
    has(key) { return key in DICT[this.lang] || key in EN; },
    t(key, params) {
      let s = DICT[this.lang][key];
      if (s == null) s = EN[key];
      if (s == null) return key;
      if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? params[k] : m));
      return s;
    },
    applyDom(root) {
      root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = this.t(el.dataset.i18n); });
      root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = this.t(el.dataset.i18nTitle); });
      root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = this.t(el.dataset.i18nPlaceholder); });
      document.title = this.t('app.title');
    },
    /** Algorithm texts in the current language. */
    info(id) {
      const base = global.SortViz.INFO.find((i) => i.id === id);
      const de = this.lang === 'de' && global.SortViz.INFO_DE ? global.SortViz.INFO_DE[id] : null;
      const src = de || base;
      return {
        name: src.name, summary: src.summary, how: src.how, steps: src.steps, trivia: src.trivia,
        tipText: de ? de.tip : base.tip && base.tip.text,
      };
    },
    _dicts: DICT,
  };

  global.SortViz.I18N = I18N;
